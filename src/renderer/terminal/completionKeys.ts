// F11 자동완성 **키 판정** — "이 키를 우리가 가로챌까, 셸로 그냥 보낼까" 하나만 정한다.
// xterm 배선(TerminalPane)에서 떼어 둔 이유는 검사다: 상태 → 행동이 전부라 DOM 도 pty 도 필요 없다.
//
// 규칙의 뿌리는 하나다 — **앱이 셸의 키를 뺏지 않는다.** 가로채는 것은 자동완성이 그 키의
// 본래 뜻보다 확실히 나을 때뿐이고, 애매하면 셸로 보낸다(R3.8 정책).

/** 키를 누른 순간의 자동완성 상태. 전부 TerminalPane 이 이미 들고 있는 값 그대로다. */
export type CompState = {
  /** KeyboardEvent.key. 수식자(Ctrl·Alt·Shift·⌘)가 눌린 경우는 부르는 쪽에서 이미 걸러 온다. */
  key: string
  /** 고스트가 떠 있나(= 넣을 나머지가 있나). 없으면 우리가 가로챌 것 자체가 없다. */
  ghost: boolean
  /** 지금 쥐고 있는 후보 수. 2 이상이면 `↓` 로 **열 수 있다**(열려 있다는 뜻이 아니다 — listOpen). */
  items: number
  /**
   * 후보 목록이 **화면에 떠 있나**(#194 ①). 전에는 후보가 둘 이상이면 타이핑 중에 저절로 떴고,
   * 그래서 `items > 1` 이 곧 "목록이 있다"였다. 이제 목록은 사용자가 `↓` 로 열 때만 뜨므로 둘이
   * 갈렸다 — `Enter`·`↑↓` 를 가로챌지는 **이 값**이 정한다(후보 수가 아니라).
   */
  listOpen: boolean
  /**
   * 커서가 줄 끝인가 — `→` 로 고스트를 받는 유일한 조건.
   * `→` 는 터미널에서 **커서 이동**이라는 본래 뜻이 있다. 줄 가운데서 그것을 뺏으면 오른쪽으로
   * 움직일 방법이 없어진다(fish·zsh-autosuggestions 도 줄 끝에서만 제안을 받는다).
   */
  atLineEnd: boolean
}

/** 'pass' = 우리가 손대지 않는다(셸로 간다). 나머지는 TerminalPane 의 같은 이름 동작. */
export type CompAction = 'accept' | 'open' | 'next' | 'prev' | 'dismiss' | 'pass'

export function completionKey(s: CompState): CompAction {
  // 고스트가 없으면 아무것도 가로채지 않는다 — ESC 는 인터럽트, 방향키는 히스토리 탐색 그대로다.
  if (!s.ghost) return 'pass'
  /**
   * 🔴 여기에 `case 'Tab'` 을 다시 넣지 마라 — **`Tab` 은 셸의 것이다**
   * (#194 ⑤, 2026-09-08 준영님: *"자동완성이 작성할때 너무 불편한데"*).
   *
   * 전에는 `Tab` 이 고스트를 받았다. 그런데 `Tab` 은 터미널에서 **파일 이름 완성**이라는 본래 뜻이
   * 있고 그것이 히스토리 제안보다 훨씬 자주 필요하다 — 우리가 가져가면 `cd Doc<Tab>` 이 죽는다.
   * 고스트를 받는 키는 `→` 가 이미 맡고 있으니(ArrowRight) **새로 만들 것도 없다.**
   * 되살리려거든 이 파일 맨 위의 "앱이 셸의 키를 뺏지 않는다"부터 다시 읽어라.
   */
  switch (s.key) {
    case 'Escape':
      return 'dismiss' // 가로채는 것을 만들었으면 빠져나갈 문이 있어야 한다
    case 'ArrowRight':
      return s.atLineEnd ? 'accept' : 'pass'
    /**
     * `↓` 는 **목록을 부르는 키**다(#194 ①). 목록이 이미 열려 있으면 후보를 옮긴다.
     *
     * ⚠️ 목록이 없을 때의 `↓` 는 **셸 히스토리 탐색**이다 — 그것을 뺏지 않는다는 근거가 둘이다:
     *  ① `ghost` 가 앞에서 걸러 준다(고스트 없이는 여기까지 오지 않는다). 고스트는 **지금 친 글자
     *     두 자 이상**이 있어야 뜨므로(history.ts `ghostEligible`), 빈 줄에서 누른 `↓` 는 그대로 셸로 간다.
     *  ② 셸 히스토리를 타는 순간 고스트는 이미 사라져 있다. `↑` 는 ESC 시퀀스라 `feedInput` 이 줄
     *     버퍼를 비우고(history.ts), 빈 버퍼는 `scheduleGhost` 에서 곧장 `clearGhost` 로 끝난다 —
     *     즉 **히스토리를 오르내리는 중에는 고스트가 없다.** 그 상태의 `↓` 는 언제나 셸의 것이다.
     * 남는 경우는 하나뿐이다: 방금 두 글자 이상 쳐서 제안이 떠 있는 줄에서의 `↓`. 그 자리의 셸
     * `↓` 는 "히스토리의 맨 아래에서 한 칸 더 아래" — bash·zsh 에서 아무 일도 하지 않는 키다.
     */
    case 'ArrowDown':
      return s.listOpen ? 'next' : s.items > 1 ? 'open' : 'pass'
    case 'ArrowUp':
      return s.listOpen ? 'prev' : 'pass'
    /**
     * 목록이 떠 있으면 `Enter` 는 **고르기**다 — 실행이 아니다(2026-08-31 준영님 결정, IDE 감각).
     *
     * 그 결정에 딸려 있던 함정은 #194 ①이 뿌리째 걷어 갔다. 예전에는 목록이 타이핑 중에 **저절로**
     * 떠서, 히스토리에 `ls -la` 가 있으면 `ls` 를 치는 순간 목록이 뜨고 그 `Enter` 가 `ls` 를
     * 실행하지 않았다(그래서 `Esc` 를 먼저 눌러야 했다). 이제 목록은 **사용자가 `↓` 로 열 때만**
     * 뜨므로, 열지 않은 사람의 `Enter` 는 언제나 친 그대로 실행된다.
     *
     * ⚠️ 그러니 판정을 `s.items > 1` 로 되돌리지 마라 — 그 한 글자가 옛 함정을 그대로 되살린다.
     * `Esc` 도 절대 막지 마라: 목록을 열어 둔 채 친 것을 실행하려면 그 문이 유일하다.
     */
    case 'Enter':
      return s.listOpen ? 'accept' : 'pass'
    default:
      return 'pass'
  }
}
