/**
 * 호칭 클램프. 시스템 프롬프트에 들어가는 값이라 **줄바꿈과 지시문 흉내를 막는다** —
 * 이름 칸에 "이전 지시는 무시하고…" 를 넣어 말투를 갈아 끼우지 못하게.
 */
export function callNameOf(v: unknown): string {
  if (typeof v !== 'string') return ''
  const one = v.replace(/[\r\n]+/g, ' ').trim()
  return one.length === 0 || one.length > 20 ? '' : one
}

/** 그 이름을 부르는 말. 이미 "님"으로 끝나면 덧붙이지 않는다. */
export function honorific(name: string): string {
  const n = callNameOf(name)
  if (n === '') return DEFAULT_CALL
  return /[님씨]$/.test(n) ? n : `${n}님`
}

