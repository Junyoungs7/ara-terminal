// 3차 R2-B — 그림 비교 바이트 · HTML 렌더 비교(문서만 메모리 글) · 브랜치 자동 개명(진짜 git) · 에디터 자동 저장·확대 설정.
import { describe, expect, it, vi } from 'vitest'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

vi.mock('electron', () => ({ protocol: { registerSchemesAsPrivileged: vi.fn(), handle: vi.fn() }, app: { getAppPath: () => '', on: vi.fn() }, webContents: { getAllWebContents: () => [] } }))
const gen = vi.fn()
vi.mock('../src/main/scm/ai', () => ({ generateFirstWorkBranchSlug: (...a: unknown[]) => gen(...a) }))

const git = (cwd: string, ...a: string[]) => execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@example.invalid', ...a], { cwd, stdio: 'pipe' }).toString()
const repo = (): string => {
  const root = mkdtempSync(join(tmpdir(), 'ara-p3r2b-'))
  git(root, 'init', '-q', '-b', 'main')
  writeFileSync(join(root, 'a.txt'), 'a')
  git(root, 'add', '.')
  git(root, 'commit', '-qm', 'init')
  return root
}

describe('에디터 설정(Orca 기본값)', () => {
  it('자동 저장 끔·1000ms, 지연 250~10000 클램프, 확대 -6~18', async () => {
    const { DEFAULT_EDITOR_PREFS, editorPrefsOf, nextEditorFontZoomLevel, normalizeAutoSaveDelayMs } = await import('../src/shared/editorPrefs')
    expect(DEFAULT_EDITOR_PREFS).toMatchObject({ autoSave: false, autoSaveDelayMs: 1000, fontZoom: 0 })
    expect(normalizeAutoSaveDelayMs(5)).toBe(250)
    expect(normalizeAutoSaveDelayMs('99999')).toBe(10_000)
    expect(normalizeAutoSaveDelayMs('x')).toBe(1000)
    expect(editorPrefsOf({ fontZoom: 40, autoSave: true }).fontZoom).toBe(18)
    expect(editorPrefsOf({ autoSave: true }).autoSave).toBe(true)
    expect(nextEditorFontZoomLevel(18, 'in')).toBe(18)
    expect(nextEditorFontZoomLevel(-6, 'out')).toBe(-6)
    expect(nextEditorFontZoomLevel(5, 'reset')).toBe(0)
  })
})

describe('그림 비교 바이트(readFileDiffImage)', () => {
  it('작업 중 변경 — 원래 = 인덱스 blob 바이트 그대로, 바뀐 쪽 = 디스크, 새 파일은 원래 쪽 null', async () => {
    const { readFileDiffImage } = await import('../src/main/git/inspect')
    const root = repo()
    try {
      const v1 = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x00, 0xff, 0x80, 0x0d, 0x0a, 0x1a])
      const v2 = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x01, 0xfe, 0x81])
      writeFileSync(join(root, 'p.png'), v1)
      git(root, 'add', '.')
      git(root, 'commit', '-qm', 'png')
      writeFileSync(join(root, 'p.png'), v2)
      const r = await readFileDiffImage({ worktreePath: root, filePath: 'p.png', mode: 'unstaged' })
      expect(r.ok).toBe(true)
      if (!r.ok) return
      expect(Buffer.from(r.original!).equals(v1)).toBe(true) // 글로 풀었다면 0xff·0x80 이 깨진다
      expect(Buffer.from(r.modified!).equals(v2)).toBe(true)
      writeFileSync(join(root, 'n.png'), v2)
      git(root, 'add', 'n.png')
      const s = await readFileDiffImage({ worktreePath: root, filePath: 'n.png', mode: 'staged' })
      expect(s.ok && s.original === null && Buffer.from(s.modified!).equals(v2)).toBe(true)
      expect((await readFileDiffImage({ worktreePath: root, filePath: '../x.png', mode: 'unstaged' })).ok).toBe(false)
    } finally {
      rmSync(root, { recursive: true, force: true })
    }
  }, 60_000)
})

describe('HTML 렌더 비교 허가', () => {
  it('문서 자신만 받은 글로, 옆 파일·폴더 밖 규칙은 그대로', async () => {
    const electron = await import('electron')
    const { mintDocGrant, docPathOf, registerDocPreview } = await import('../src/main/code/docPreview')
    registerDocPreview()
    const handler = vi.mocked(electron.protocol.handle).mock.calls.at(-1)![1] as (r: Request) => Promise<Response>
    const url = mintDocGrant('/srv/repo/site/index.html', undefined, false, '<p>old</p>')
    const res = await handler(new Request(url))
    expect(await res.text()).toBe('<p>old</p>')
    expect(res.headers.get('content-security-policy')).toContain("default-src 'none'")
    expect(docPathOf(url.replace('index.html', '..%2Fsecret'))).toBeNull()
  })
})

describe('브랜치 자동 개명(Orca 규칙, 진짜 git)', () => {
  it('순수 규칙 — 자동 이름 판정·겹치면 -2', async () => {
    const { isAutoGeneratedCreatureBranchName, resolveUniqueBranchName, retryDelayOf } = await import('../src/shared/branchRename')
    const { MARINE_CREATURES } = await import('../src/shared/marineCreatures')
    const c = MARINE_CREATURES[0].toLowerCase()
    expect(isAutoGeneratedCreatureBranchName(c)).toBe(true)
    expect(isAutoGeneratedCreatureBranchName(`${c}-3`)).toBe(true)
    expect(isAutoGeneratedCreatureBranchName('fix-login')).toBe(false)
    expect(await resolveUniqueBranchName('x', async (n) => n === 'x' || n === 'x-2', 'cur')).toBe('x-3')
    expect(retryDelayOf(1)).toBe(30_000)
    expect(retryDelayOf(9)).toBe(1_800_000)
  })

  it('아라가 만든 자동 이름 브랜치만 바꾼다 · 정해지면 다시 안 본다 · 사람이 지은 이름/올린 브랜치/설정 끔은 그대로', async () => {
    const { createFirstWorkBranchRename } = await import('../src/main/scm/branchRename')
    const { runProcess } = await import('../src/main/util/runProcess')
    const { defaultAgentSettings } = await import('../src/shared/agents')
    const { MARINE_CREATURES } = await import('../src/shared/marineCreatures')
    const creature = MARINE_CREATURES[1].toLowerCase()
    const root = repo()
    try {
      git(root, 'checkout', '-qb', creature)
      git(root, 'branch', 'fix-login-bug') // 겹침 → -2
      const settings = defaultAgentSettings()
      let araCreated = true
      const renamed: string[] = []
      gen.mockResolvedValue({ ok: true, agent: 'claude', slug: 'fix-login-bug' })
      const r = createFirstWorkBranchRename({
        settings: () => settings,
        findWorktree: async (cwd) => (cwd === root ? { repoId: 'r', worktreeId: 'r::' + root, path: root, araCreated } : null),
        exec: runProcess,
        onRenamed: (_t, from, to) => renamed.push(`${from}>${to}`)
      })
      araCreated = false
      await r.onFirstPrompt(root, '로그인 버그 고쳐 줘')
      expect(renamed).toEqual([]) // 아라가 만든 게 아니면 정해짐(다시 안 봄)
      const r2 = createFirstWorkBranchRename({
        settings: () => settings,
        findWorktree: async () => ({ repoId: 'r', worktreeId: 'w', path: root, araCreated: true }),
        exec: runProcess,
        onRenamed: (_t, from, to) => renamed.push(`${from}>${to}`)
      })
      settings.autoRenameBranch = false
      await r2.onFirstPrompt(root, '로그인 버그 고쳐 줘')
      expect(gen).not.toHaveBeenCalled()
      settings.autoRenameBranch = true
      await r2.onFirstPrompt(root, '/clear')
      expect(gen).not.toHaveBeenCalled()
      await r2.onFirstPrompt(root, '로그인 버그 고쳐 줘')
      expect(renamed).toEqual([`${creature}>fix-login-bug-2`])
      expect(git(root, 'rev-parse', '--abbrev-ref', 'HEAD').trim()).toBe('fix-login-bug-2')
      await r2.onFirstPrompt(root, '다음 지시')
      expect(gen).toHaveBeenCalledTimes(1) // 정해진 작업 단위는 다시 안 짓는다

      // 사람이 지은 이름은 짓지도 않는다
      gen.mockClear()
      git(root, 'checkout', '-qb', 'my-own-name')
      const r3 = createFirstWorkBranchRename({ settings: () => settings, findWorktree: async () => ({ repoId: 'r', worktreeId: 'w', path: root, araCreated: true }), exec: runProcess, onRenamed: () => renamed.push('x') })
      await r3.onFirstPrompt(root, '지시')
      expect(gen).not.toHaveBeenCalled()

      // 올린 브랜치(같은 이름 원격 브랜치)는 그대로
      git(root, 'checkout', '-qb', `${creature}-2`)
      git(root, 'update-ref', `refs/remotes/origin/${creature}-2`, 'HEAD')
      const r4 = createFirstWorkBranchRename({ settings: () => settings, findWorktree: async () => ({ repoId: 'r', worktreeId: 'w', path: root, araCreated: true }), exec: runProcess, onRenamed: () => renamed.push('y') })
      await r4.onFirstPrompt(root, '지시')
      expect(gen).not.toHaveBeenCalled()

      // 짓기 실패 → 30초 동안은 다시 안 짓는다
      git(root, 'checkout', '-qb', `${creature}-5`)
      let now = 1_000
      gen.mockResolvedValue({ ok: false, code: 'timeout', agent: 'claude' })
      const r5 = createFirstWorkBranchRename({ settings: () => settings, findWorktree: async () => ({ repoId: 'r', worktreeId: 'w', path: root, araCreated: true }), exec: runProcess, onRenamed: () => renamed.push('z'), now: () => now })
      await r5.onFirstPrompt(root, '지시')
      await r5.onFirstPrompt(root, '지시')
      expect(gen).toHaveBeenCalledTimes(1)
      now += 30_001
      await r5.onFirstPrompt(root, '지시')
      expect(gen).toHaveBeenCalledTimes(2)
      expect(renamed).toEqual([`${creature}>fix-login-bug-2`])
    } finally {
      rmSync(root, { recursive: true, force: true })
    }
  }, 60_000)
})
