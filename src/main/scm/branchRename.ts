// 규칙(Orca 그대로): 설정 켬(기본) · 작업 단위의 첫 지시가 들어온 때(에이전트 실행 지시·훅 UserPromptSubmit) · **아라가 만든** 작업 단위(meta.createdAt) ·
// 브랜치 끝 이름이 자동 이름(바다 생물, -n 꼬리 하나까지) · 올린 적 없는 브랜치(upstream·같은 이름 원격 브랜치 없음)일 때만.
// 이름 = 사용자 PC 의 CLI 에이전트를 한 번(소스 제어 [AI 로 쓰기]와 같은 길 — 첫 지시가 그 모델로 간다). 짓는 동안 브랜치가 바뀌거나 올라가면 그만둔다.
// 정해진 판정(바꿈·대상 아님)은 기억해 다시 안 본다. 실패(사용량 한도 등)는 30초 → 2분 → 30분 뒤 다음 지시에서 다시.
// 뺀 것(Orca): 폴더 이름 바꾸기(Orca 도 꺼 둠 ENABLE_FIRST_WORK_FOLDER_RENAME=false) · 표시 이름 따로 고정(아라 표시 이름 = 브랜치) ·
// 실패 배지·진단 창(AutoRenameFailedDialog — 아라는 오류 로그 한 줄) · 브랜치 접두어 설정 · 원격(SSH) 작업 단위(Orca 도 SSH 는 미루고 안 함) · 폴더 작업 공간 제목 바꾸기.
import type { AgentSettings } from '@shared/agents'
import { isAutoGeneratedCreatureBranchName, resolveUniqueBranchName, retryDelayOf } from '@shared/branchRename'
import type { Exec } from '../work/backend'
import { generateFirstWorkBranchSlug } from './ai'

export type FirstWorkTarget = { repoId: string; worktreeId: string; path: string; araCreated: boolean }
export type FirstWorkRenameDeps = {
  settings: () => AgentSettings
  /** cwd → 그 작업 단위(로컬 git 프로젝트만). 못 찾으면 null. */
  findWorktree: (cwd: string) => Promise<FirstWorkTarget | null>
  exec: Exec
  /** 바꾼 뒤 — 렌더러가 목록을 다시 읽는다. */
  onRenamed: (t: FirstWorkTarget, from: string, to: string) => void
  log?: (msg: string) => void
  now?: () => number
}

const SETTLED_CAP = 500

export function createFirstWorkBranchRename(deps: FirstWorkRenameDeps) {
  const settled = new Set<string>()
  const inFlight = new Set<string>()
  const failures = new Map<string, { count: number; retryAt: number }>()
  const now = deps.now ?? Date.now
  const log = deps.log ?? (() => {})
  const remember = (key: string): void => {
    settled.delete(key)
    settled.add(key)
    while (settled.size > SETTLED_CAP) settled.delete(settled.values().next().value as string)
  }

  /** true = 정해짐(다시 안 봄), false = 다음 지시에서 다시. */
  async function run(key: string, t: FirstWorkTarget, prompt: string, assistant: string | undefined): Promise<boolean> {
    const git = (args: string[]) => deps.exec('git', args, { cwd: t.path, timeoutMs: 15_000, env: { GIT_TERMINAL_PROMPT: '0' } })
    const branchOf = async (): Promise<string> => {
      const r = await git(['rev-parse', '--abbrev-ref', 'HEAD'])
      return r.code === 0 ? r.stdout.trim() : ''
    }
    // 올린 브랜치는 그대로(Orca probeBranchUpstream — 원격 브랜치·열린 리뷰가 고아가 된다). 판정 실패면 다음에 다시.
    const published = async (branch: string): Promise<boolean | null> => {
      const u = await git(['rev-parse', '--abbrev-ref', '--symbolic-full-name', '@{u}'])
      if (u.code === 0 && u.stdout.trim()) return true
      if (u.code !== 0 && !/no upstream|does not point to a branch|unknown revision|bad revision/i.test(u.stderr)) return null
      const remote = await git(['for-each-ref', '--format=%(refname)', `refs/remotes/*/${branch}`])
      if (remote.code !== 0) return null
      return remote.stdout.trim().length > 0
    }
    const current = await branchOf()
    if (!current || current === 'HEAD') return false // 브랜치가 아직 없다(detached) — 다음에
    if (!t.araCreated) return true
    const leaf = current.slice(current.lastIndexOf('/') + 1)
    if (!isAutoGeneratedCreatureBranchName(leaf)) return true
    const pub = await published(current)
    if (pub === null) return false
    if (pub) return true
    const settings = deps.settings()
    const gen = await generateFirstWorkBranchSlug({ root: t.path, x: deps.exec, remote: false, settings }, prompt, assistant)
    if (!gen.ok || !gen.slug) {
      const count = (failures.get(key)?.count ?? 0) + 1
      failures.set(key, { count, retryAt: now() + retryDelayOf(count) })
      log(`branch auto-rename: generation failed (${gen.ok ? 'empty' : gen.code}) for ${t.path}`)
      return false
    }
    // 짓는 동안 브랜치가 바뀌었거나 올라갔으면 그만(다음 지시에서 다시 본다).
    if ((await branchOf()) !== current || (await published(current)) !== false) return false
    const prefix = current.slice(0, current.lastIndexOf('/') + 1) // 자동 이름 앞에 붙은 접두어(있으면) 유지
    const exists = async (name: string): Promise<boolean> => (await git(['show-ref', '--verify', '--quiet', `refs/heads/${prefix}${name}`])).code === 0
    const unique = await resolveUniqueBranchName(gen.slug, exists, leaf)
    if (!unique || unique === leaf) return true
    const next = prefix + unique
    const mv = await git(['branch', '-m', next])
    if (mv.code !== 0) {
      log(`branch auto-rename: git branch -m failed for ${t.path}: ${mv.stderr.trim()}`)
      return false
    }
    log(`branch auto-rename: ${current} -> ${next} (${t.path})`)
    deps.onRenamed(t, current, next)
    return true
  }

  return {
    /** 작업 단위의 첫 지시(에이전트 탭의 cwd). 매 지시마다 불러도 된다 — 정해진 작업 단위는 바로 돌아간다. */
    async onFirstPrompt(cwd: string, prompt: unknown, assistant?: string): Promise<void> {
      if (typeof prompt !== 'string' || !prompt.trim() || prompt.trim().startsWith('/')) return
      if (!deps.settings().autoRenameBranch) return
      // 판정은 탭의 cwd(= 작업 단위 폴더)로 기억한다 — 정해진 작업 단위는 git 을 다시 부르지 않는다.
      const f = failures.get(cwd)
      if (settled.has(cwd) || inFlight.has(cwd) || (f && now() < f.retryAt)) return
      inFlight.add(cwd)
      try {
        const t = await deps.findWorktree(cwd)
        if (!t) return remember(cwd) // 아라 프로젝트의 로컬 작업 단위가 아니다
        if (await run(cwd, t, prompt.trim(), assistant)) {
          failures.delete(cwd)
          remember(cwd)
        }
      } catch (e) {
        log(`branch auto-rename: ${e instanceof Error ? e.message : String(e)}`)
      } finally {
        inFlight.delete(cwd)
      }
    }
  }
}
export type FirstWorkBranchRename = ReturnType<typeof createFirstWorkBranchRename>
